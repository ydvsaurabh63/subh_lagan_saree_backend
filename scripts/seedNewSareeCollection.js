async function seed() {
  try {
    console.log('Connecting to MongoDB Atlas...');
    await mongoose.connect(process.env.MONGO_URI);
    console.log('Connected to MongoDB successfully.');

    // Fetch all categories
    const categories = await Category.find({}).lean();
    const catMap = {};
    categories.forEach((cat) => {
      catMap[cat.slug] = cat._id;
    });

    // Fallback category if slug not matched
    const defaultCatId = catMap['banarasi-sarees'] || categories[0]?._id;

    let addedCount = 0;
    let updatedCount = 0;

    for (const item of NEW_SAREES) {
      const catId = catMap[item.categorySlug] || defaultCatId;
      const productData = {
        name: item.name,
        slug: item.slug,
        sku: item.sku,
        description: item.description,
        category: catId,
        images: item.images,
        price: item.price,
        discountPrice: item.discountPrice,
        fabric: item.fabric,
        color: item.color,
        sareeLength: item.sareeLength,
        blouseDetails: item.blouseDetails,
        occasion: item.occasion,
        stock: item.stock,
        isFeatured: item.isFeatured,
        isBestSeller: item.isBestSeller,
        isNewArrival: item.isNewArrival,
        isBridal: item.isBridal,
        ratings: item.ratings,
        numReviews: item.numReviews,
        storeSlug: 'subh-lagan',
        storeName: 'Subh Lagan Sarees',
        storeType: 'saree',
      };

      const existing = await Product.findOne({ slug: item.slug });
      if (existing) {
        await Product.updateOne({ slug: item.slug }, { $set: productData });
        updatedCount++;
      } else {
        await Product.create(productData);
        addedCount++;
      }
    }

    console.log(`\n🎉 SEED SUCCESS: Added ${addedCount} new sarees, Updated ${updatedCount} existing sarees.`);

    const totalSubh = await Product.countDocuments({
      $or: [{ storeSlug: 'subh-lagan' }, { storeSlug: null }, { storeSlug: { $exists: false } }],
    });
    console.log(`Total Subh Lagan sarees in database now: ${totalSubh}`);

    process.exit(0);
  } catch (err) {
    console.error('Error seeding sarees:', err);
    process.exit(1);
  }
}

seed();

